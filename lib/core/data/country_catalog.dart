/// 'fr'), falling back to Spanish then to the raw code if a language or
/// code isn't found.
String countryDisplayName(String countryCode, [String languageCode = 'es']) {
  final code = countryCode.toLowerCase();
  final table = switch (languageCode) {
    'en' => countryNamesEn,
    'fr' => countryNamesFr,
    _ => countryNamesEs,
  };
  return table[code] ?? countryNamesEs[code] ?? countryCode.toUpperCase();
}

/// Regional-indicator flag emoji for an ISO 3166-1 alpha-2 code. Computed
/// rather than bundled as assets — every pair of regional-indicator
/// symbols renders as a flag on Android/iOS without needing image files.
String countryFlagEmoji(String countryCode) {
  final code = countryCode.toUpperCase();
  if (code.length != 2) return '🏳️';
  const base = 0x1F1E6;
  const aCode = 0x41;
  final first = base + (code.codeUnitAt(0) - aCode);
  final second = base + (code.codeUnitAt(1) - aCode);
  if (first < base ||
      first > base + 25 ||
      second < base ||
      second > base + 25) {
    return '🏳️';
  }
  return String.fromCharCode(first) + String.fromCharCode(second);
}
