"""Regenerates src/pages/privacidad.astro from the app's in-app privacy
policy (lib/features/legal/privacy_policy_text.dart), so the website and
the app always show the same text. Run from website/: python scripts/sync-privacy.py
"""
import html
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
dart = (root.parent / 'lib/features/legal/privacy_policy_text.dart').read_text(encoding='utf-8')
text = dart[dart.index("'''") + 3:dart.rindex("'''")].strip()


def inline(t: str) -> str:
    t = html.escape(t, quote=False)
    t = re.sub(r'(https?://[^\s<]+)', r'<a href="\1" target="_blank" rel="noopener">\1</a>', t)
    t = re.sub(r'([\w.+-]+@[\w-]+\.[\w.]+)', r'<a href="mailto:\1">\1</a>', t)
    # Astro would treat braces as expressions.
    return t.replace('{', '&#123;').replace('}', '&#125;')


out = []
for block in text.split('\n\n'):
    block = block.strip()
    if block.startswith('Última actualización'):
        out.append(f'<p class="updated">{inline(block)}</p>')
    elif block.startswith('# '):
        out.append(f'<h2>{inline(block[2:])}</h2>')
    elif all(line.startswith('- ') for line in block.split('\n')):
        items = '\n'.join(f'    <li>{inline(l[2:])}</li>' for l in block.split('\n'))
        out.append(f'  <ul>\n{items}\n  </ul>')
    else:
        out.append('<p>' + '<br />\n'.join(inline(l) for l in block.split('\n')) + '</p>')

body = '\n  '.join(out)
page = f"""---
// GENERATED by scripts/sync-privacy.py from the app's privacy policy text.
// Edit lib/features/legal/privacy_policy_text.dart and re-run the script.
import Layout from '../layouts/Layout.astro';
---

<Layout title="Política de privacidad · Kipack" description="Cómo trata Kipack tus datos.">
  <article class="prose">
  <h1>Política de privacidad</h1>
  {body}
  </article>
</Layout>
"""
(root / 'src/pages/privacidad.astro').write_text(page, encoding='utf-8', newline='\n')
print('privacidad.astro updated')
